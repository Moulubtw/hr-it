export function difficultyRules(d: Difficulty): string {
  const r = DIFFICULTY_RULES[d];
  const base: Record<Difficulty, string> = {
    gentle:
      "Режим «Щадящий»: никакого давления. Задавай вопросы по одному, простыми словами. Если ответ слабый, можешь мягко подсказать направление в реакции. Уточняющих вопросов не задавай.",
    medium:
      "Режим «Средний»: обычное собеседование. Если ответ расплывчатый, можешь задать не больше одного уточняющего вопроса по той же теме.",
    hard:
      "Режим «Сложный»: стресс‑интервью. Задавай неудобные вопросы, вопросы‑ловушки, проверяй противоречия с предыдущими ответами, требуй цифры и конкретику. Можешь задать до двух уточняющих вопросов подряд по одной теме.",
  };
  return `${base[d]} Лимит уточняющих вопросов подряд: ${r.maxFollowUps}.`;
}

